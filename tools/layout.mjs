// Door layout generator. Reads a design's keep-out zones and day-24 door from
// src/designs/<id>.js, packs doors 1-23 so each door AND the space its flap swings
// into never overlap another door, flap or keep-out zone, then writes src/layouts/<id>.js.
// Usage: node tools/layout.mjs <id> [tries=300] [seeds=1,2,...]
import fs from 'node:fs';
import vm from 'node:vm';
const [, , id, triesArg = '300', seedsArg = '1,2,3,4,5,6,7,8'] = process.argv;
if (!id) { console.error('usage: node tools/layout.mjs <design-id>'); process.exit(1); }
const ctx = { window: {}, console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('src/util.js', 'utf8'), ctx);
vm.runInContext(fs.readFileSync(`src/designs/${id}.js`, 'utf8'), ctx);
const design = ctx.window.AYY.designs[id];
if (!design) { console.error('design not registered as AYY.designs.' + id); process.exit(1); }
const W = design.width, H = design.height;
const cfg = { margin: 26, gap: 12, keepOut: design.keepOut || [], fixed: [{ day: 24, ...design.day24, hinge: 'double' }], minSize: design.minDoor || 96, maxSize: design.maxDoor || 150 };
function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6d2b79f5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const foot = (d) => {
  if (d.hinge === 'left') return [d.x - d.w, d.y, d.w * 2, d.h];
  if (d.hinge === 'right') return [d.x, d.y, d.w * 2, d.h];
  if (d.hinge === 'top') return [d.x, d.y - d.h, d.w, d.h * 2];
  return [d.x - d.w / 2, d.y, d.w * 2, d.h];
};
const hit = (a, b, g) => a[0] < b[0] + b[2] + g && b[0] < a[0] + a[2] + g && a[1] < b[1] + b[3] + g && b[1] < a[1] + a[3] + g;
function attempt(R) {
  const placed = cfg.fixed.map((d) => ({ ...d, f: foot(d) }));
  const ok = (f) => f[0] >= cfg.margin && f[1] >= cfg.margin && f[0] + f[2] <= W - cfg.margin && f[1] + f[3] <= H - cfg.margin
    && !cfg.keepOut.some((b) => hit(f, b, 4)) && !placed.some((p) => hit(f, p.f, cfg.gap));
  for (let i = 0; i < 23; i++) {
    let done = false;
    for (let size = cfg.maxSize; size >= cfg.minSize && !done; size -= 6) {
      for (let k = 0; k < 900 && !done; k++) {
        const ar = 0.75 + R() * 0.55;
        let w = Math.round((size * (ar > 1 ? 1 : ar)) / 2) * 2, h = Math.round((size * (ar > 1 ? 1 / ar : 1)) / 2) * 2;
        if (R() < 0.5) [w, h] = [h, w];
        const r = R();
        const hinge = r < 0.42 ? 'left' : r < 0.84 ? 'right' : 'top';
        const d = { x: Math.round(cfg.margin + R() * (W - 2 * cfg.margin)), y: Math.round(cfg.margin + R() * (H - 2 * cfg.margin)), w, h, hinge };
        const f = foot(d);
        if (ok(f)) { placed.push({ ...d, f }); done = true; }
      }
    }
    if (!done) return null;
  }
  return placed;
}
let best = null, bestScore = -1, bestSeed = 0;
for (const seed of seedsArg.split(',').map(Number)) {
  for (let t = 0; t < Number(triesArg); t++) {
    const res = attempt(rng(seed * 1000 + t));
    if (!res) continue;
    const areas = res.map((d) => d.w * d.h);
    const score = areas.reduce((a, b) => a + b, 0) + 40 * Math.min(...areas);
    if (score > bestScore) { bestScore = score; best = res; bestSeed = seed; }
  }
}
if (!best) { console.error(`No layout fits for ${id}. Shrink keep-out zones or lower minDoor.`); process.exit(1); }
const R = rng(bestSeed);
const nums = Array.from({ length: 23 }, (_, i) => i + 1);
for (let i = nums.length - 1; i > 0; i--) { const j = Math.floor(R() * (i + 1)); [nums[i], nums[j]] = [nums[j], nums[i]]; }
let n = 0;
const doors = best.map((d) => ({ day: d.day || nums[n++], x: d.x, y: d.y, w: d.w, h: d.h, hinge: d.hinge })).sort((a, b) => a.day - b.day);
fs.writeFileSync(`src/layouts/${id}.js`, `/* Door layout for "${design.name}" (board units). Generated by tools/layout.mjs; hinge = side the flap swings toward. */\n(function(){const A=(window.AYY=window.AYY||{});A.layouts=A.layouts||{};\nA.layouts[${JSON.stringify(id)}]=${JSON.stringify(doors).replace(/\},\{/g, '},\n{')};\n})();\n`);
console.log(`${id}: wrote src/layouts/${id}.js  smallest door ${Math.min(...best.map((d) => d.w * d.h))} px2`);
